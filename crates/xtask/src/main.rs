//! Generates `packages/range/src/generated/constants.ts` from this workspace's own
//! `spotlab-range` constants, run via `cargo xtask codegen` (see `.cargo/config.toml`).
//! Mirrors the `src-tauri/xtask` precedent: the main app's `src/tauri/codegen.ts` renders its
//! `RANKS` / `SUITS` constants through `tauri-specta`'s `.constant()`, whose implementation is
//! just `serde_json::to_value(v)` — not anything specta-specific. This crate does the same
//! conversion directly, with no specta dependency, so `RANKS` / `SUITS` / `COMBOS` have exactly
//! one Rust-side definition each, with TypeScript generated from it rather than duplicating it.

use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::PathBuf;
use std::process::ExitCode;

use serde_json::Value;
use spotlab_range::{COMBOS, RANKS, SUITS};

fn print_usage() {
    eprintln!("usage: cargo xtask <task>");
    eprintln!();
    eprintln!("tasks:");
    eprintln!(
        "  codegen   Regenerate packages/range/src/generated/constants.ts from spotlab-range's constants"
    );
}

/// Resolves relative to this crate's own manifest directory, so the command works regardless of
/// the caller's current working directory.
fn output_path() -> PathBuf {
    let mut path = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    path.pop(); // -> crates
    path.pop(); // -> spotlab
    path.push("packages");
    path.push("range");
    path.push("src");
    path.push("generated");
    path.push("constants.ts");
    path
}

fn json_string(value: &Value) -> &str {
    value
        .as_str()
        .expect("RANKS/SUITS/COMBOS serialize as JSON strings")
}

/// Renders a string array as `[a, b, c]` on one line if it's short enough to read comfortably,
/// otherwise wraps it to `per_line` quoted elements per row.
fn render_array(values: &[Value], per_line: usize, single_line_max: usize) -> String {
    let quoted: Vec<String> = values
        .iter()
        .map(|v| format!("\"{}\"", json_string(v)))
        .collect();
    if quoted.len() <= single_line_max {
        return format!("[{}]", quoted.join(", "));
    }
    let mut out = String::from("[\n");
    for chunk in quoted.chunks(per_line) {
        out.push_str("  ");
        out.push_str(&chunk.join(", "));
        out.push_str(",\n");
    }
    out.push(']');
    out
}

fn generate() -> String {
    let ranks = serde_json::to_value(RANKS).expect("RANKS serializes to JSON");
    let suits = serde_json::to_value(SUITS).expect("SUITS serializes to JSON");
    // `serde`'s array impl is macro-generated only up to length 32; COMBOS has 169 elements, so
    // serialize it as a slice instead, which has a generic impl for any length.
    let combos = serde_json::to_value(COMBOS.as_slice()).expect("COMBOS serializes to JSON");

    let mut out = String::new();
    out.push_str(
        "// This file is generated by `cargo xtask codegen` (crates/xtask).\n\
         // Do not edit it by hand — change the constants in\n\
         // `crates/spotlab-range/src/constants.rs` and regenerate instead.\n\n",
    );
    writeln!(
        out,
        "/** The 13 rank characters, ascending (`'2'..'A'`). */\nexport const RANKS = {} as const;\n",
        render_array(ranks.as_array().unwrap(), 13, 4)
    )
    .unwrap();
    writeln!(
        out,
        "/** The 4 suit characters (`c`, `d`, `h`, `s`). */\nexport const SUITS = {} as const;\n",
        render_array(suits.as_array().unwrap(), 4, 4)
    )
    .unwrap();
    writeln!(
        out,
        "/** The 169 canonical combos in the hand matrix's row-major order. */\nexport const COMBOS = {} as const;\n",
        render_array(combos.as_array().unwrap(), 13, 4)
    )
    .unwrap();
    out.truncate(out.trim_end().len());
    out.push('\n');
    out
}

fn run_codegen() -> Result<(), String> {
    let output = output_path();
    let contents = generate();
    if let Some(parent) = output.parent() {
        fs::create_dir_all(parent)
            .map_err(|e| format!("failed to create {}: {e}", parent.display()))?;
    }
    fs::write(&output, contents)
        .map_err(|e| format!("failed to write {}: {e}", output.display()))?;
    println!("wrote {}", output.display());
    Ok(())
}

fn main() -> ExitCode {
    let task = env::args().nth(1);
    let result = match task.as_deref() {
        Some("codegen") => run_codegen(),
        Some(other) => {
            eprintln!("unknown task: {other}");
            print_usage();
            return ExitCode::from(2);
        }
        None => {
            print_usage();
            return ExitCode::from(2);
        }
    };

    match result {
        Ok(()) => ExitCode::SUCCESS,
        Err(err) => {
            eprintln!("error: {err}");
            ExitCode::FAILURE
        }
    }
}
